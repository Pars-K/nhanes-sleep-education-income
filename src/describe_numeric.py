"""خلاصه متغیرهای کمی و بررسی حساسیت خلاصه خواب به دو گروه انتهایی."""

from pathlib import Path

import pandas as pd

from audit_adults import markdown_table


ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "reports/phase1"
VARIABLES = {
    "SLD012": ("خواب روزهای کاری؛ با تقریب دو گروه انتهایی", "ساعت"),
    "SLD013": ("خواب روزهای غیرکاری؛ با تقریب دو گروه انتهایی", "ساعت"),
    "RIDAGEYR": ("سن ثبت‌شده؛ با گروه 80 سال و بالاتر", "سال"),
    "INDFMPIR": ("نسبت درآمد ثبت‌شده؛ با گروه 5 و بیشتر", "بدون واحد"),
}


def summarize(values):
    values = values.dropna()
    if len(values) < 2:
        raise ValueError("برای محاسبه انحراف معیار دست‌کم دو مشاهده لازم است.")
    q1, median, q3 = values.quantile([0.25, 0.5, 0.75], interpolation="linear")
    return {
        "تعداد": len(values),
        "میانگین": values.mean(),
        "میانه": median,
        "انحراف معیار": values.std(ddof=1),
        "چارک اول": q1,
        "چارک سوم": q3,
        "دامنه میان‌چارکی": q3 - q1,
        "کمینه ثبت‌شده": values.min(),
        "بیشینه ثبت‌شده": values.max(),
    }


def formatted(frame):
    result = frame.copy()
    for col in result.select_dtypes(include="floating").columns:
        result[col] = result[col].map(lambda value: f"{value:.3f}")
    return result


def main():
    demo = pd.read_sas(ROOT / "data/raw/DEMO_L.xpt", format="xport", encoding=None)
    sleep = pd.read_sas(ROOT / "data/raw/SLQ_L.xpt", format="xport", encoding=None)
    if demo.SEQN.isna().any() or sleep.SEQN.isna().any():
        raise ValueError("شناسه گمشده در فایل خام وجود دارد.")
    merged = demo.merge(sleep, on="SEQN", how="left", validate="one_to_one")
    adults = merged.loc[merged.RIDAGEYR.ge(20)]
    main_rows, sensitivity_rows = [], []
    comparisons = []
    for col, (label, unit) in VARIABLES.items():
        values = adults[col]
        main = summarize(values)
        main_rows.append({
            "نام متغیر": col, "متغیر": label, "واحد": unit,
            "تعداد ناموجود": int(values.isna().sum()), **main,
        })
        if col in ("SLD012", "SLD013"):
            without_end_groups = values.loc[~values.isin([2, 14])]
            sensitivity = summarize(without_end_groups)
            end_count = int(values.isin([2, 14]).sum())
            if main["تعداد"] - sensitivity["تعداد"] != end_count:
                raise ValueError("تعداد مشاهدات مقایسه با شمار دو گروه انتهایی سازگار نیست.")
            sensitivity_rows.append({
                "نام متغیر": col,
                "متغیر": "خواب روزهای کاری" if col == "SLD012" else "خواب روزهای غیرکاری",
                "تعداد دو گروه انتهایی": end_count,
                **sensitivity,
                "تغییر میانگین نسبت به تقریب اصلی؛ دقیقه":
                    60 * (sensitivity["میانگین"] - main["میانگین"]),
                "تغییر انحراف معیار؛ ساعت":
                    sensitivity["انحراف معیار"] - main["انحراف معیار"],
            })
            comparisons.append((main, sensitivity))

    main_table = pd.DataFrame(main_rows)
    sensitivity_table = pd.DataFrame(sensitivity_rows)
    OUT.mkdir(parents=True, exist_ok=True)
    main_table.to_csv(OUT / "numeric_summaries.csv", index=False, encoding="utf-8-sig")
    sensitivity_table.to_csv(OUT / "sleep_sensitivity.csv", index=False, encoding="utf-8-sig")
    weekday, weekend = comparisons
